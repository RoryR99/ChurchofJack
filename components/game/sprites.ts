export type SpriteName = keyof typeof SPR;

export function makeSprite(rows: string[], remap?: Record<string, string>, flip = false) {
  const h = rows.length;
  const w = rows[0].length;
  const c = document.createElement("canvas");
  c.width = w;
  c.height = h;
  const x = c.getContext("2d")!;
  rows.forEach((row, y) => {
    for (let i = 0; i < w; i++) {
      let ch = row[i];
      if (ch === ".") continue;
      if (remap && remap[ch]) ch = remap[ch];
      x.fillStyle = PAL[+ch];
      x.fillRect(flip ? w - 1 - i : i, y, 1, 1);
    }
  });
  return c;
}

